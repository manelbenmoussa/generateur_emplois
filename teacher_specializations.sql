-- 14. Create trigger to enforce 16-hour weekly limit per teacher
CREATE OR REPLACE FUNCTION check_teacher_weekly_hours()
RETURNS TRIGGER AS $$
DECLARE
    total_hours DECIMAL(5,2);
    new_subject_hours DECIMAL(3,1);
    teacher_max_hours DECIMAL(3,1) := 16.0;
BEGIN
    -- Get the hour volume of the new/updated subject
    SELECT hour_volume INTO new_subject_hours 
    FROM "Subject" 
    WHERE id = NEW.subject_id;

    -- Calculate current total hours for this teacher
    SELECT COALESCE(SUM(s.hour_volume), 0) INTO total_hours
    FROM "sessions" se
    JOIN "Subject" s ON se.subject_id = s.id
    WHERE se.teacher_id = NEW.teacher_id
    AND se.id != COALESCE(NEW.id, 0); -- Exclude current session if updating

    -- Add the new session's hours
    total_hours := total_hours + new_subject_hours;

    -- Check if limit is exceeded
    IF total_hours > teacher_max_hours THEN
        RAISE EXCEPTION 'Teacher % cannot teach more than % hours per week. Current: % + New: % = % hours',
            NEW.teacher_id, teacher_max_hours, (total_hours - new_subject_hours), new_subject_hours, total_hours;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Drop trigger if exists and create new one
DROP TRIGGER IF EXISTS enforce_teacher_hours ON "sessions";
CREATE TRIGGER enforce_teacher_hours
    BEFORE INSERT OR UPDATE ON "sessions"
    FOR EACH ROW
    EXECUTE FUNCTION check_teacher_weekly_hours();

